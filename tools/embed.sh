#!/bin/sh
# Write an assembler file that holds the weight files and a C table naming
# them. Usage: embed.sh out.S out.c weights-dir...
# Taken from the directories: the newest neuronte-split-vN.nrt and every
# neuronte-term-*.nrt. A name found twice is taken from the first directory.
set -eu
asm=$1; table=$2; shift 2

list=$(mktemp)
trap 'rm -f "$list"' EXIT

best=""; best_v=-1
for dir in "$@"; do
    for f in "$dir"/neuronte-split-v*.nrt; do
        [ -f "$f" ] || continue
        v=${f##*/neuronte-split-v}; v=${v%.nrt}
        case $v in ''|*[!0-9]*) continue ;; esac
        if [ "$v" -gt "$best_v" ]; then best_v=$v; best=$f; fi
    done
done
[ -n "$best" ] && printf '%s\n' "$best" >"$list"

for dir in "$@"; do
    for f in "$dir"/neuronte-term-*.nrt; do
        [ -f "$f" ] || continue
        name=${f##*/}
        grep -q "/$name\$" "$list" || printf '%s\n' "$f" >>"$list"
    done
done

{
    echo '/* Generated by tools/embed.sh. */'
    echo '    .section .rodata'
    i=0
    while IFS= read -r f; do
        echo "    .balign 16"
        echo "    .globl neuroterm_w$i"
        echo "    .globl neuroterm_w${i}_end"
        echo "neuroterm_w$i:"
        echo "    .incbin \"$f\""
        echo "neuroterm_w${i}_end:"
        i=$((i + 1))
    done <"$list"
    echo '    .section .note.GNU-stack,"",%progbits'
} >"$asm"

{
    echo '/* Generated by tools/embed.sh. */'
    echo 'struct embedded { const char *name; const unsigned char *start, *end; };'
    i=0
    while IFS= read -r f; do
        echo "extern const unsigned char neuroterm_w$i[], neuroterm_w${i}_end[];"
        i=$((i + 1))
    done <"$list"
    echo 'const struct embedded neuroterm_embedded[] = {'
    i=0
    while IFS= read -r f; do
        echo "    {\"${f##*/}\", neuroterm_w$i, neuroterm_w${i}_end},"
        i=$((i + 1))
    done <"$list"
    echo '    {0, 0, 0}'
    echo '};'
} >"$table"
